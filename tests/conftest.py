# ---- R reference files ---------------------------------------------------------------

def read_ref(name: str, strings=STRING_COLUMNS) -> pd.DataFrame:
    """Read a reference table written by make_r_reference.R (17 significant digits)."""
    raw = pd.read_csv(REF_DIR / f"{name}.csv.gz", dtype=str, keep_default_na=False)
    result = {}
    for column in raw.columns:
        values = raw[column]
        if column in strings:
            result[column] = values.replace({"NA": None}) if column in ("predicted", "group") else values
            continue
        if values.isin(["TRUE", "FALSE", "NA"]).all():
            result[column] = values.map({"TRUE": True, "FALSE": False, "NA": None})
            if result[column].isna().any():
                result[column] = result[column].astype("boolean")
            else:
                result[column] = result[column].astype(bool)
            continue
        numeric = values.replace({"NA": "nan", "NaN": "nan"})
        try:
            result[column] = numeric.map(float) if not numeric.str.fullmatch(r"-?\d+").all() else numeric.astype(np.int64)
        except ValueError:
            result[column] = values
    return pd.DataFrame(result, columns=raw.columns)


def read_ref_matrix(name: str) -> pd.DataFrame:
    """Read a matrix written with write_matrix() (first column holds row names)."""
    raw = pd.read_csv(REF_DIR / f"{name}.csv.gz", dtype=str, keep_default_na=False)
    index = raw.pop("row")
    values = raw.replace({"NA": "nan", "NaN": "nan", "inf": "inf", "-inf": "-inf"}).map(float)
    values.index = index.to_numpy()
    return values


def read_ref_vector(name: str, numeric: bool = False):
    return read_ref(name, strings=set() if numeric else {"value"})["value"].tolist()


#: Tolerances for floating point values compared with R (or between Python code paths).
RTOL = 1e-9
ATOL = 1e-12


def assert_markers_equal(python: pd.DataFrame, r: pd.DataFrame, rtol: float = RTOL, atol: float = ATOL):
    """Check a Python table against an R table: same columns and rows (in order), close values.

    Strings, integers and booleans must be identical, floats close (NaN at the same places).
    """
    assert list(python.columns) == list(r.columns)
    assert len(python) == len(r)
    for column in python.columns:
        p, q = python[column].reset_index(drop=True), r[column].reset_index(drop=True)
        if column in STRING_COLUMNS:
            np.testing.assert_array_equal(p.astype(object).fillna("<NA>").astype(str),
                                          q.astype(object).fillna("<NA>").astype(str), err_msg=column)
        elif pd.api.types.is_bool_dtype(q.dtype) or str(q.dtype) == "boolean":
            assert _as_bool_list(p) == _as_bool_list(q), column
        elif pd.api.types.is_integer_dtype(q.dtype) and pd.api.types.is_integer_dtype(p.dtype):
            np.testing.assert_array_equal(p.to_numpy(), q.to_numpy(), err_msg=column)
        else:
            np.testing.assert_allclose(p.to_numpy(dtype=np.float64), q.to_numpy(dtype=np.float64),
                                       rtol=rtol, atol=atol, err_msg=column)


def assert_matrix_close(python, expected, rtol: float = RTOL, atol: float = ATOL):
    np.testing.assert_allclose(np.asarray(python, dtype=np.float64), np.asarray(expected, dtype=np.float64),
                               rtol=rtol, atol=atol)


def _as_bool_list(values: pd.Series) -> list:
    return [None if pd.isna(v) else bool(v) for v in values]


def assert_same_ranking(python: pd.DataFrame, r: pd.DataFrame, rtol: float = RTOL):
    """Meta-marker rankings agree up to near-ties (values that differ by less than rtol)."""
    keys = ["group", "cell_type"]
    assert len(python) == len(r)
    for key, a in python.groupby(keys, sort=False):
        b = r[(r["group"] == key[0]) & (r["cell_type"] == key[1])]
        a, b = a.sort_values("rank"), b.sort_values("rank")
        np.testing.assert_array_equal(a["recurrence"].to_numpy(), b["recurrence"].to_numpy())
        np.testing.assert_allclose(a["auroc"].to_numpy(), b["auroc"].to_numpy(), rtol=rtol)
        assert set(a["gene"]) == set(b["gene"])


# ---- datasets --------------------------------------------------------------------------

@dataclass
class Dataset:
    name: str
    counts: sp.spmatrix      # cells x genes
    cpm: sp.spmatrix
    label: np.ndarray
    cell_class: np.ndarray
    genes: np.ndarray        # vignette gene names (var["symbol"])
    cells: np.ndarray

    @property
    def logcpm(self):
        result = self.cpm.copy()
        result.data = np.log1p(result.data)
        return result


def vignette_labels(name: str, obs: pd.DataFrame) -> pd.Series:
    """Harmonized cell type names, as in the R vignettes."""
    if name == "baron":
        return obs["label"].astype(str).replace({"activated_stellate": "mesenchymal", "quiescent_stellate": "mesenchymal"})
    if name == "muraro":
        return obs["label"].astype(str).replace({"duct": "ductal", "pp": "gamma"})
    labels = obs["cell type"].astype(object)
    labels = labels.where(labels.isna(), labels.astype(str).str.replace(" cell", "", regex=False))
    return labels.replace({"PSC": "mesenchymal"})


def load_dataset(name: str, common_labels) -> Dataset:
    import anndata as ad

    adata = ad.read_h5ad(H5AD_DIR / f"{FILES[name]}.h5ad")
    labels = vignette_labels(name, adata.obs)
    keep = labels.isin(common_labels).to_numpy()
    counts = adata.X[keep]
    label = labels[keep].to_numpy(dtype=object)
    return Dataset(
        name=name, counts=counts, cpm=mm.convert_to_cpm(counts), label=label,
        cell_class=np.where(np.isin(label, list(ENDOCRINE)), "endocrine", "non-endocrine").astype(object),
        genes=adata.var["symbol"].astype(str).to_numpy(dtype=object),
        cells=np.asarray(adata.obs_names[keep]),
    )


